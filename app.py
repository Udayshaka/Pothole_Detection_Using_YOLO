import io
from pathlib import Path

import streamlit as st
from PIL import Image
from ultralytics import YOLO


# -------------------- Page configuration --------------------
st.set_page_config(
    page_title="Pothole Detection using YOLO",
    page_icon="🛣️",
    layout="wide",
)

st.title("🛣️ Pothole Detection using YOLO")
st.write(
    "Upload a road image and the trained YOLO model will identify potholes "
    "and display the detected bounding boxes."
)

# -------------------- Model loading --------------------
DEFAULT_MODEL_PATH = Path("/Users/uday/Desktop/CNN_Project /best .pt")


@st.cache_resource
def load_model(model_path: str):
    """Load and cache the YOLO model so it is not reloaded on every rerun."""
    return YOLO(model_path)


with st.sidebar:
    st.header("Model settings")
    st.caption(
        "Place your trained best.pt file in the same folder as app.py, "
        "or upload the weights below."
    )

    uploaded_weights = st.file_uploader(
        "Upload trained YOLO weights (.pt)",
        type=["pt"],
        help="Use the best.pt file generated by your notebook training run.",
    )
    confidence = st.slider(
        "Confidence threshold",
        min_value=0.10,
        max_value=0.95,
        value=0.70,
        step=0.05,
    )
    image_size = st.select_slider(
        "Inference image size",
        options=[320, 416, 512, 640, 768, 1024],
        value=640,
    )

# Save uploaded weights to a temporary local file for Ultralytics.
model_path = str(DEFAULT_MODEL_PATH)
if uploaded_weights is not None:
    uploaded_model_path = Path("uploaded_model.pt")
    uploaded_model_path.write_bytes(uploaded_weights.getvalue())
    model_path = str(uploaded_model_path)

# -------------------- Image upload --------------------
uploaded_image = st.file_uploader(
    "Choose a road image",
    type=["jpg", "jpeg", "png", "bmp", "webp"],
)

if uploaded_image is None:
    st.info("Upload a JPG, JPEG, PNG, BMP, or WEBP image to start detection.")
    st.stop()

image = Image.open(io.BytesIO(uploaded_image.getvalue())).convert("RGB")

left, right = st.columns(2)
with left:
    st.subheader("Original image")
    st.image(image, use_container_width=True)

# -------------------- Run detection --------------------
if st.button("🔍 Detect potholes", type="primary", use_container_width=True):
    if not Path(model_path).is_file():
        st.error(
            "Trained model weights were not found. Put best.pt beside app.py "
            "or upload your best.pt file in the sidebar."
        )
        st.stop()

    try:
        with st.spinner("Loading model and detecting potholes..."):
            model = load_model(model_path)
            results = model.predict(
                source=image,
                conf=confidence,
                imgsz=image_size,
                verbose=False,
            )

        result = results[0]
        annotated_image = result.plot()  # Ultralytics returns a BGR NumPy image.
        annotated_image = Image.fromarray(annotated_image[:, :, ::-1])

        with right:
            st.subheader("Detection result")
            st.image(annotated_image, use_container_width=True)

        boxes = result.boxes
        detection_count = 0 if boxes is None else len(boxes)

        st.divider()
        st.subheader("Detection summary")
        metric_col1, metric_col2 = st.columns(2)
        metric_col1.metric("Objects detected", detection_count)
        metric_col2.metric("Confidence threshold", f"{confidence:.0%}")

        if detection_count == 0:
            st.warning(
                "No potholes were detected above the selected confidence "
                "threshold. Try lowering the threshold."
            )
        else:
            rows = []
            names = result.names
            for box in boxes:
                class_id = int(box.cls.item())
                score = float(box.conf.item())
                x1, y1, x2, y2 = [round(float(v), 1) for v in box.xyxy[0].tolist()]
                rows.append(
                    {
                        "Class": names.get(class_id, str(class_id)),
                        "Confidence": f"{score:.1%}",
                        "X1": x1,
                        "Y1": y1,
                        "X2": x2,
                        "Y2": y2,
                    }
                )

            st.dataframe(rows, use_container_width=True, hide_index=True)

        # Allow the annotated result to be downloaded.
        output = io.BytesIO()
        annotated_image.save(output, format="PNG")
        st.download_button(
            "⬇️ Download detected image",
            data=output.getvalue(),
            file_name="pothole_detection_result.png",
            mime="image/png",
        )

    except Exception as exc:
        st.error(f"Detection failed: {exc}")
        st.caption(
            "Check that best.pt is a valid Ultralytics YOLO weights file and "
            "that the installed package versions are compatible."
        )

st.caption(
    "Model: your fine-tuned YOLO11 weights. Results depend on the training "
    "dataset and the quality of the uploaded image."
)
